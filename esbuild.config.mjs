import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
// pdf-parse/pdf.js: fix for Electron renderer (Obsidian) environment
// 1. Set disableWorker on window.PDFJS so pdf.js skips real Worker creation
//    (pdf.js reads disableWorker from _global_scope.default.PDFJS = window.PDFJS)
// 2. Polyfill require.ensure so pdf.js can load bundled worker code via fake worker
//    (without this, fakeWorkerFilesLoader stays null and fake worker path also fails)
try{if(typeof window!=='undefined'){window.PDFJS=window.PDFJS||{};window.PDFJS.disableWorker=true;}}catch(e){}
try{if(typeof require!=='undefined'&&typeof require.ensure==='undefined'){require.ensure=function(d,c){c();};}}catch(e){}
`;

const prod = (process.argv[2] === "production");

// 内部命令（微信读书快捷入口 + 调试/测试命令）剥离开关。
// 值为字符串 'true' | 'false'（非 boolean），经 JSON.stringify 注入为 esbuild define 字面量：
// - INTERNAL_COMMANDS 显式优先（deploy.js 按 target 注入：dev=保留 / daily=剥离）
// - 未设时 fail-safe：production 构建剥离（正式版语义），dev watch 保留
const internalCommandsFlag = process.env.INTERNAL_COMMANDS !== undefined
    ? process.env.INTERNAL_COMMANDS
    : (prod ? 'false' : 'true');

const context = await esbuild.context({
    banner: {
        js: banner,
    },
    define: {
        'process.env.DEV_COMMANDS': JSON.stringify(internalCommandsFlag),
    },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtins,
        // Node.js built-in modules with node: prefix
        "node:fs",
        "node:fs/promises",
        "node:path",
        "node:crypto",
        "node:os",
        "node:util",
        "node:stream",
        "node:events",
        // Dynamic imports - loaded at runtime
        "./pageindex/vault/*",
        "./pageindex/parsers/pdf-to-markdown"],
    format: "cjs",
    target: "es2018",
    loader: { ".jpg": "dataurl" },
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    minify: prod,
    keepNames: true,
    outfile: "bin/main.js",
});

if (prod) {
    await context.rebuild();
    process.exit(0);
} else {
    await context.watch();
}
