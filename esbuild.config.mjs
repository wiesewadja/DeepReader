import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
// pdf-parse/pdf.js: disable web worker to avoid workerSrc error in Electron/E2E
// Must run BEFORE any pdf.js code evaluates typeof Worker checks
try{Object.defineProperty(window,'Worker',{get(){return undefined;},configurable:true});}catch(e){}
try{Object.defineProperty(global,'Worker',{get(){return undefined;},configurable:true});}catch(e){}
`;

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
    banner: {
        js: banner,
    },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: [
        "obsidian",
        "electron",
        "@codemirror/autocomplete",
        "@codemirror/collab",
        "@codemirror/commands",
        "@codemirror/language",
        "@codemirror/lint",
        "@codemirror/search",
        "@codemirror/state",
        "@codemirror/view",
        "@lezer/common",
        "@lezer/highlight",
        "@lezer/lr",
        ...builtins,
        // Node.js built-in modules with node: prefix
        "node:fs",
        "node:fs/promises",
        "node:path",
        "node:crypto",
        "node:os",
        "node:util",
        "node:stream",
        "node:events",
        // Dynamic imports - loaded at runtime
        "./pageindex/vault/*",
        "./pageindex/parsers/pdf-to-markdown"],
    format: "cjs",
    target: "es2018",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    outfile: "bin/main.js",
});

if (prod) {
    await context.rebuild();

    // Post-build patch: replace pdf.js workerSrc errors with fake worker fallback
    const fs = await import("fs");
    let mainJs = fs.readFileSync("bin/main.js", "utf-8");
    const patchCount = mainJs.split('throw new Error("No PDFJS.workerSrc specified")').length - 1;
    mainJs = mainJs.replaceAll(
        'throw new Error("No PDFJS.workerSrc specified")',
        'console.warn("[pdf-parse] No workerSrc, using fake worker");return null'
    );
    fs.writeFileSync("bin/main.js", mainJs);
    console.log(`[post-build] Patched ${patchCount} pdf.js workerSrc errors`);

    process.exit(0);
} else {
    await context.watch();
}
