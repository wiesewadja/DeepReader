// ==================== 图标类型定义 ====================

/**
 * 所有可用的图标名称
 */
export type IconName = keyof typeof Icons;

/**
 * 图标尺寸预设
 */
export type IconSize = 14 | 16 | 20 | 24;

/**
 * 图标配置选项
 */
export interface IconOptions {
	/** 自定义宽度 */
	width?: number;
	/** 自定义高度 */
	height?: number;
	/** 额外的 CSS 类名 */
	className?: string;
	/** 是否旋转（用于加载动画） */
	spin?: boolean;
}

/**
 * 图标值类型（所有 SVG 字符串的联合类型）
 */
export type IconValue = typeof Icons[IconName];

// ==================== 图标工具函数 ====================

/**
 * 获取图标 SVG 字符串
 * @param name 图标名称
 * @param options 图标选项
 * @returns SVG HTML 字符串
 */
export function getIcon(name: IconName, options?: IconOptions): string {
	let svg = Icons[name] as string;

	if (!svg) {
		console.warn(`[Icons] 图标 "${name}" 不存在，使用默认图标`);
		svg = Icons.info as string;
	}

	if (options) {
		// 调整尺寸
		if (options.width !== undefined || options.height !== undefined) {
			const width = options.width || 16;
			const height = options.height || 16;
			svg = svg.replace(/width="[^"]*"/, `width="${width}"`);
			svg = svg.replace(/height="[^"]*"/, `height="${height}"`);
		}

		// 添加 CSS 类
		if (options.className) {
			svg = svg.replace('<svg', `<svg class="${options.className}"`);
		}

		// 添加旋转动画
		if (options.spin) {
			svg = svg.replace('<svg', `<svg style="animation: spin 1s linear infinite;"`);
		}
	}

	return svg;
}

/**
 * 创建图标 DOM 元素
 * @param name 图标名称
 * @param options 图标选项
 * @returns HTML 元素
 */
export function createIconElement(name: IconName, options?: IconOptions): HTMLElement {
	const div = document.createElement('div');
	div.innerHTML = getIcon(name, options);
	const svg = div.firstElementChild;

	if (!svg) {
		console.warn(`[Icons] 无法创建图标元素 "${name}"`);
		return div;
	}

	if (!(svg instanceof HTMLElement)) {
		console.warn(`[Icons] 图标元素不是 HTMLElement "${name}"`);
		return div;
	}

	return svg;
}

/**
 * 检查图标是否存在
 * @param name 图标名称
 * @returns 是否存在
 */
export function hasIcon(name: string): name is IconName {
	return name in Icons;
}

/**
 * 获取所有可用的图标名称
 * @returns 图标名称数组
 */
export function getAvailableIcons(): IconName[] {
	return Object.keys(Icons) as IconName[];
}

