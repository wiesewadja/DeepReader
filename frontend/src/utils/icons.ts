/**
 * 带有 spin 动画的加载图标
 * @returns SVG HTML 字符串
 */
export function getSpinnerIcon(): string {
	return getIcon('spinner', { spin: true });
}

/**
 * 获取状态图标
 * @param status 状态字符串
 * @returns 对应的图标 SVG
 */
export function getStatusIcon(status: 'loading' | 'success' | 'warning' | 'error'): string {
	switch (status) {
		case 'loading':
			return getSpinnerIcon();
		case 'success':
			return getIcon('check');
		case 'warning':
			return getIcon('warning');
		case 'error':
			return getIcon('x');
		default:
			return getIcon('info');
	}
}
